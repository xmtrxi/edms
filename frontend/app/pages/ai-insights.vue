<script setup lang="ts">
  import {
    SparklesIcon,
    ShieldAlertIcon,
    TagIcon,
    Link2Icon,
    FileTextIcon,
    SendIcon,
    Loader2Icon,
    Trash2Icon,
    CheckCircle2Icon,
    PlusIcon,
  } from "@lucide/vue";
  import { ref, shallowRef, computed } from "vue";
  import { toast } from "vue-sonner";

  import { Badge } from "@/components/ui/badge";
  import { Button } from "@/components/ui/button";
  import {
    Dialog,
    DialogContent,
    DialogHeader,
    DialogTitle,
    DialogDescription,
    DialogFooter,
  } from "@/components/ui/dialog";
  import {
    Select,
    SelectContent,
    SelectItem,
    SelectTrigger,
    SelectValue,
  } from "@/components/ui/select";
  import { insights as seedInsights, type AIInsight } from "@/data/mock-data";
  import { cn } from "@/lib/utils";

  definePageMeta({
    title: "AI Insights",
    description:
      "Summaries, classifications, risks, and entity extraction generated by your private AI.",
    breadcrumbs: [{ label: "Collaboration", to: "/" }, { label: "AI Insights" }],
  });

  useHead({
    title: "AI Insights — Lumen DMS",
    meta: [
      {
        name: "description",
        content:
          "AI-generated summaries, classifications, risks, and entity extraction across your documents.",
      },
    ],
  });

  const typeMeta: Record<string, { Icon: typeof FileTextIcon; color: string; label: string }> = {
    summary: { Icon: FileTextIcon, color: "text-primary", label: "Summary" },
    risk: { Icon: ShieldAlertIcon, color: "text-warning", label: "Risk" },
    classification: { Icon: TagIcon, color: "text-info", label: "Classification" },
    entity: { Icon: TagIcon, color: "text-success", label: "Entities" },
    related: { Icon: Link2Icon, color: "text-violet-500", label: "Related" },
  };

  const suggestions = [
    "Find expiring NDAs",
    "Risky liability caps",
    "Summarize Q3 financials",
    "Show GDPR-flagged docs",
  ];

  const insightTypes = ["all", "summary", "risk", "classification", "entity", "related"] as const;

  const insights = shallowRef<AIInsight[]>(seedInsights);
  const prompt = ref("");
  const answer = ref<string | null>(null);
  const thinking = ref(false);
  const genOpen = ref(false);
  const askFocused = ref(false);
  const typeFilter = ref<(typeof insightTypes)[number]>("all");

  const filtered = computed(() => {
    if (typeFilter.value === "all") return insights.value;
    return insights.value.filter((i) => i.type === typeFilter.value);
  });

  const countsByType = computed(() => {
    const counts: Record<string, number> = { all: insights.value.length };
    for (const t of insightTypes.slice(1)) {
      counts[t] = insights.value.filter((i) => i.type === t).length;
    }
    return counts;
  });

  function ask(q?: string) {
    const query = (q ?? prompt.value).trim();
    if (!query) return;
    prompt.value = query;
    answer.value = null;
    thinking.value = true;
    setTimeout(() => {
      thinking.value = false;
      answer.value = `Across 34,886 documents, ${Math.floor(Math.random() * 12) + 3} match "${query}". Top signals: 2 contracts with auto-renewal in 90 days, 1 vendor risk above policy, and 4 related policies. I cited 6 sources for review.`;
    }, 900);
  }

  function dismiss(id: string) {
    insights.value = insights.value.filter((x) => x.id !== id);
    toast("Insight dismissed", {
      action: {
        label: "Undo",
        onClick: () => {
          insights.value = [...insights.value, seedInsights.find((s) => s.id === id)!];
        },
      },
    });
  }

  function handleKeydown(e: KeyboardEvent) {
    if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) {
      e.preventDefault();
      ask();
    }
  }

  const dotColor = (type: string) => {
    const map: Record<string, string> = {
      summary: "bg-primary",
      risk: "bg-warning",
      classification: "bg-info",
      entity: "bg-success",
      related: "bg-violet-500",
    };
    return map[type] ?? "bg-muted-foreground";
  };
</script>

<template>
  <Teleport to="#page-actions-target">
    <Button size="sm" class="gap-1.5" @click="genOpen = true">
      <SparklesIcon class="h-4 w-4" /> Generate
    </Button>
  </Teleport>

  <div class="space-y-5">
    <!-- AI Ask -->
    <div class="border-border/60 bg-card rounded-xl border shadow-sm">
      <div class="flex items-center gap-2 px-3 py-2.5">
        <SparklesIcon class="text-primary h-4 w-4 shrink-0" />
        <input
          v-model="prompt"
          placeholder="Ask AI about your documents..."
          class="placeholder:text-muted-foreground/40 flex-1 bg-transparent text-sm outline-none"
          @focus="askFocused = true"
          @keydown="handleKeydown"
        />
        <Button
          size="sm"
          class="h-7 gap-1 px-2 text-xs"
          :disabled="thinking || !prompt.trim()"
          @click="ask()"
        >
          <Loader2Icon v-if="thinking" class="h-3 w-3 animate-spin" />
          <SendIcon v-else class="h-3 w-3" />
          Ask
        </Button>
      </div>
      <div v-if="askFocused && !thinking && !answer" class="flex flex-wrap gap-1 px-3 pb-2.5">
        <button
          v-for="s in suggestions"
          :key="s"
          @click="ask(s)"
          class="bg-secondary/50 hover:bg-secondary text-muted-foreground hover:text-foreground rounded-md px-2 py-0.5 text-[11px] transition-colors"
        >
          {{ s }}
        </button>
      </div>
      <div
        v-if="thinking || answer"
        class="border-border/40 border-t px-3 py-2 text-xs leading-relaxed"
      >
        <div v-if="thinking" class="text-muted-foreground flex items-center gap-1.5">
          <Loader2Icon class="h-3 w-3 animate-spin" /> Analyzing your libraries&hellip;
        </div>
        <div v-else class="text-foreground/80 flex items-start gap-1.5">
          <SparklesIcon class="text-primary mt-0.5 h-3.5 w-3.5 shrink-0" />
          <span>{{ answer }}</span>
        </div>
      </div>
    </div>

    <!-- Filter -->
    <div class="flex items-center gap-1 overflow-x-auto pb-0.5">
      <button
        v-for="t in insightTypes"
        :key="t"
        @click="typeFilter = t"
        :class="
          cn(
            'flex shrink-0 items-center gap-1.5 rounded-md px-2.5 py-1 text-xs font-medium whitespace-nowrap transition-all',
            typeFilter === t
              ? 'bg-foreground text-background'
              : 'text-muted-foreground hover:text-foreground hover:bg-secondary/70',
          )
        "
      >
        <component :is="t === 'all' ? SparklesIcon : typeMeta[t].Icon" class="h-3.5 w-3.5" />
        {{ typeMeta[t]?.label ?? "All" }}
        <span
          :class="
            cn(
              'ml-0.5 text-[10px] tabular-nums',
              typeFilter === t ? 'text-background/60' : 'text-muted-foreground/50',
            )
          "
          >{{ countsByType[t] ?? 0 }}</span
        >
      </button>
    </div>

    <!-- Insights -->
    <div v-if="filtered.length === 0" class="flex flex-col items-center py-16 text-center">
      <CheckCircle2Icon class="text-muted-foreground/20 h-8 w-8" />
      <p class="text-muted-foreground mt-2 text-sm font-medium">No insights</p>
      <p class="text-muted-foreground/60 mt-0.5 text-xs">
        Adjust your filter or generate new ones.
      </p>
      <Button size="sm" class="mt-3 gap-1.5" @click="genOpen = true"
        ><SparklesIcon class="h-3.5 w-3.5" /> Generate</Button
      >
    </div>

    <div v-else class="space-y-0.5">
      <div
        v-for="i in filtered"
        :key="i.id"
        class="group hover:bg-accent/30 flex items-start gap-2.5 rounded-lg px-3 py-2.5 transition-colors"
      >
        <div :class="cn('mt-1.5 h-2 w-2 shrink-0 rounded-full', dotColor(i.type))" />
        <div class="min-w-0 flex-1">
          <div class="flex items-center gap-2">
            <span class="text-muted-foreground/70 text-[11px] font-medium">{{
              typeMeta[i.type].label
            }}</span>
            <span
              v-if="i.severity"
              class="text-[10px] font-medium"
              :class="
                i.severity === 'high'
                  ? 'text-destructive'
                  : i.severity === 'medium'
                    ? 'text-warning'
                    : 'text-muted-foreground/60'
              "
              >{{ i.severity }}</span
            >
          </div>
          <p class="mt-0.5 text-sm leading-snug font-medium">{{ i.title }}</p>
          <p class="text-muted-foreground/80 mt-0.5 line-clamp-2 text-xs leading-relaxed">
            {{ i.detail }}
          </p>
          <div class="mt-1.5 flex items-center gap-2">
            <span class="text-muted-foreground/60 flex items-center gap-1 text-[11px]">
              <FileTextIcon class="h-3 w-3" />
              <span class="max-w-[200px] truncate">{{ i.doc }}</span>
            </span>
            <span
              class="text-[11px] tabular-nums"
              :class="
                i.confidence > 0.9
                  ? 'text-success'
                  : i.confidence > 0.7
                    ? 'text-warning'
                    : 'text-muted-foreground/60'
              "
              >{{ Math.round(i.confidence * 100) }}%</span
            >
            <div class="bg-secondary/50 h-0.5 max-w-[80px] flex-1 overflow-hidden rounded-full">
              <div
                class="h-full rounded-full"
                :class="
                  i.confidence > 0.9
                    ? 'bg-success'
                    : i.confidence > 0.7
                      ? 'bg-warning'
                      : 'bg-muted-foreground/20'
                "
                :style="{ width: `${i.confidence * 100}%` }"
              />
            </div>
          </div>
        </div>
        <div
          class="flex shrink-0 items-center gap-1 opacity-0 transition-opacity group-hover:opacity-100"
        >
          <button
            class="hover:bg-secondary/80 text-muted-foreground/60 hover:text-foreground rounded p-1"
            @click="toast.info('Opening ' + i.doc)"
          >
            <FileTextIcon class="h-3.5 w-3.5" />
          </button>
          <button
            class="hover:bg-secondary/80 text-muted-foreground/60 hover:text-foreground rounded p-1"
            @click="dismiss(i.id)"
          >
            <Trash2Icon class="h-3.5 w-3.5" />
          </button>
        </div>
      </div>
    </div>
  </div>

  <Dialog :open="genOpen" @update:open="(v: boolean) => (genOpen = v)">
    <DialogContent>
      <DialogHeader>
        <DialogTitle class="flex items-center gap-2 text-base"
          ><SparklesIcon class="text-primary h-4 w-4" /> Generate insights</DialogTitle
        >
        <DialogDescription class="text-xs"
          >Run a fresh AI pass across the selected scope. Results appear in this
          view.</DialogDescription
        >
      </DialogHeader>
      <div class="space-y-3">
        <div class="space-y-1.5">
          <p class="text-xs font-medium">Scope</p>
          <Select :model-value="'all'">
            <SelectTrigger><SelectValue /></SelectTrigger>
            <SelectContent>
              <SelectItem value="all">All accessible libraries</SelectItem>
              <SelectItem value="legal">Legal Vault</SelectItem>
              <SelectItem value="finance">Finance Hub</SelectItem>
              <SelectItem value="hr">People Ops</SelectItem>
            </SelectContent>
          </Select>
        </div>
        <div class="grid grid-cols-2 gap-2 text-xs">
          <label
            v-for="c in ['Summaries', 'Risk detection', 'Classification', 'Entity extraction']"
            :key="c"
            class="border-border bg-secondary/30 hover:bg-secondary/60 flex cursor-pointer items-center gap-2 rounded-lg border px-3 py-2.5 transition-colors"
          >
            <input type="checkbox" default-checked class="accent-primary rounded" /> {{ c }}
          </label>
        </div>
      </div>
      <DialogFooter>
        <Button variant="ghost" @click="genOpen = false">Cancel</Button>
        <Button
          @click="
            genOpen = false;
            toast('Insight generation queued — 6 new results will appear shortly.', {
              action: { label: 'View', onClick: () => {} },
            });
          "
        >
          <SparklesIcon class="mr-1.5 h-3.5 w-3.5" /> Run
        </Button>
      </DialogFooter>
    </DialogContent>
  </Dialog>
</template>
